package org.eclipse.persistence.jpa.fetchdefaults.model;

import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.MappedSuperclass;

@MappedSuperclass
public class DefaultFetchMappedSuperclass {
    private int id;
    private DefaultFetchTarget inheritedTarget;

    @Id
    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    @ManyToOne
    @JoinColumn(name = "INHERITED_ID")
    public DefaultFetchTarget getInheritedTarget() {
        return inheritedTarget;
    }

    public void setInheritedTarget(DefaultFetchTarget inheritedTarget) {
        this.inheritedTarget = inheritedTarget;
    }
}
